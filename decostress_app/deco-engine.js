/* ---- decompression obligation (the real one) ------------------------------
   Ported from benchmark/profile.py::_schedule -- the ceiling-driven ascent.
   From the current tissue state, repeatedly: if the Bühlmann ceiling is
   shallower than where you are, travel up to it at 30 fsw/min; otherwise hold
   a 10-fsw stop until it clears. The total is the ascent the physics DEMANDS.

   This is the key to using the fitted model honestly. In the Navy trials
   ascent time was never the diver's choice -- it was the prescribed schedule.
   Feed the model an ascent time the diver invented and it inverts (a fast
   ascent looks "safe"). Feed it the OBLIGATION and it is correctly signed:
   deeper and longer -> bigger obligation -> higher risk. Verified monotonic in
   both depth and bottom time.                                                */
const ASCENT_FSW_PER_MIN=30.0, DESCENT_FSW_PER_MIN=60.0, STOP_FSW=10.0, DT_SCHED=0.5;
const K_C = HALF.map(h=>Math.LN2/h);

function ceilingFsw(P){
  let tol=-Infinity;
  for(let c=0;c<NC;c++) tol=Math.max(tol,(P[c]-A_C[c])*B_C[c]);   // gf = 1.0
  return Math.max(0,(tol-P_SURFACE)/FSW_TO_BAR);
}
function haldane(P,pAlv,dt){
  const out=new Array(NC);
  for(let c=0;c<NC;c++) out[c]=pAlv+(P[c]-pAlv)*Math.exp(-K_C[c]*dt);
  return out;
}
const alvAtFsw = fsw => (P_SURFACE+fsw*FSW_TO_BAR)*FN2;

/* Minutes of ascent the ceiling demands from this tissue state at this depth.
   This is a dive computer's "time to surface". */
function requiredAscentMin(P, depthFsw){
  let d=depthFsw, travel=0, stop=0;
  let Pt=P.slice();
  for(let i=0;i<4000;i++){
    if(d<=0) break;
    const target=Math.min(Math.ceil(ceilingFsw(Pt)/STOP_FSW)*STOP_FSW, d);
    if(target<d){
      const dt=(d-target)/ASCENT_FSW_PER_MIN;
      Pt=haldane(Pt,alvAtFsw((d+target)/2),dt);
      travel+=dt; d=target;
    }else{
      Pt=haldane(Pt,alvAtFsw(d),DT_SCHED);
      stop+=DT_SCHED;
    }
  }
  return {total:travel+stop, travel, stop};
}
/* Tissue state after descending to depth and sitting there for bottomMin. */
function loadToBottom(depthFsw, bottomMin){
  let P=new Array(NC).fill(P_SURFACE*FN2);
  const desc=Math.max(depthFsw/DESCENT_FSW_PER_MIN,DT_SCHED);
  const n=Math.max(Math.ceil(desc/DT_SCHED),1);
  for(let i=0;i<n;i++) P=haldane(P,alvAtFsw(depthFsw*(i+1)/n),desc/n);
  const nb=Math.max(Math.ceil(bottomMin/DT_SCHED),1);
  for(let i=0;i<nb;i++) P=haldane(P,alvAtFsw(depthFsw),bottomMin/nb);
  return P;
}

/* Reduce any profile to the three scalars the model was fitted on.
   USN convention: bottom time runs from leaving the surface to the start
   of the final ascent; ascent time is the rest. */
function diveScalars(poly){
  if(!poly || poly.length<2) return null;
  const tEnd=poly[poly.length-1].t;
  const maxD=Math.max.apply(null,poly.map(p=>p.d));

  /* bottom_time is TIME AT DEPTH -- it excludes the descent.
     This has to match the CSV column the model was fitted on, and
     benchmark/profile.py settles it: _materialise() lays out
     descent(desc_min) THEN bottom(bottom_time_min), and _load_to_bottom()
     descends and THEN sits for bottom_time_min. So descent is separate.

     Counting from t=0 instead (i.e. "time until leaving the bottom") inflates
     bottom time by the descent, and then loadToBottom descends a SECOND time --
     which overstated the deco obligation by ~1.5 min on a 30 m dive.

     Ascent is everything after the last moment at max depth, including any
     decompression or safety stops. */
  let iArrive=poly.length-1, iLeave=0;
  for(let j=0;j<poly.length;j++) if(poly[j].d >= maxD-1e-9){ iArrive=Math.min(iArrive,j); iLeave=j; }
  const bottom=Math.max(poly[iLeave].t - poly[iArrive].t, 0.1);
  const ascent=Math.max(tEnd-poly[iLeave].t, 0.1);

  /* Out of distribution: the model saw square bounce dives. Reducing a
     multi-level or sawtooth profile to three scalars silently throws its shape
     away, so detect a RE-DESCENT (the diver went back down after coming up).
     Compress flats first -- a flat bottom otherwise splits the peak and hides it. */
  const seq=[];
  for(const q of poly) if(!seq.length || Math.abs(q.d-seq[seq.length-1])>0.5) seq.push(q.d);
  let redescents=0, wentUp=false;
  for(let j=1;j<seq.length;j++){
    if(seq[j] < seq[j-1]) wentUp=true;              // rising toward the surface
    else if(seq[j] > seq[j-1] && wentUp) redescents++;  // back down again
  }
  return {depthFsw:maxD*M_TO_FSW, bottom, ascent, maxDepthM:maxD, multilevel:redescents>=1};
}
/* Standardise -> linear score -> percentile within the real cohort.
   NOTE sc.ascent here MUST be the required obligation, not the diver's choice. */
function realScore(sc){
  const x=[sc.depthFsw, sc.bottom, sc.ascent];
  let z=RM.intercept;
  for(let i=0;i<3;i++) z += RM.coef[i]*((x[i]-RM.mean[i])/RM.scale[i]);
  return z;
}

/* THE REAL PREDICTION.
   Scores a profile the way the Navy data was actually generated: the dive
   determines an obligation, and the obligation is what the model sees.
   Also reports whether the diver actually HONOURED that obligation -- if they
   surfaced early, the dive is off the map (no Navy diver skipped their deco,
   so the model has never seen such a dive and must not be asked about it). */
/* ---- profile audit: ONE continuous pass, read by every surface --------------

   The bug this replaces: violation was judged by comparing ascent MINUTES to a
   required obligation rebuilt from a square approximation. On a square dive that
   coincides with the truth; on a sawtooth it diverges completely, so a dive that
   surfaced bent (five compartments over the limit) was shown "MILDER THAN MOST
   NAVY DIVES." The honest question is not "did you spend enough minutes
   ascending" but "were you ever physically over your ceiling, and can the model
   even see this dive."

   Two facts, deliberately separate:
     violated       -- a physical fact: max_t (ceiling - depth) over the REAL
                       trajectory exceeded tolerance, OR you surfaced over the
                       surfacing M-value. Checked continuously, not at the end;
                       fast tissues that bust the ceiling at depth off-gas before
                       you surface, so the surfacing snapshot alone lies.
     inDistribution -- an epistemic fact: reducing this dive to (depth, bottom,
                       ascent) loses no material physics, i.e. the real profile
                       and the square the model implicitly assumes audit the same.
                       If not, the 3-scalar rank is meaningless -- the model was
                       fitted on square bounce dives and never saw this shape.

   The rank may be shown only when inDistribution AND not violated.

   CEIL_TOL clears the ~0.6 m transient overshoot that correctly-staged deco
   dives incur from 10-fsw stop rounding; genuine breaches are >= 2 m. Ratio to
   the surfacing M-value is only meaningful AT the surface, so the continuous
   test is ceiling-minus-current-depth, never peak load ratio (which is ~1.4x on
   every legitimate deco dive). GF is 1.0 -- the raw ZHL-16A table, the most
   permissive line there is; treat the boundary as "at the edge," not "safe."   */
const CEIL_TOL_M = 1.0;

function walkAudit(poly){
  let t=HALF.map(()=>inspN2(0)); const dt=0.02;
  let maxOverM=-1e9, minutesOver=0, peakRate=0;
  for(let i=1;i<poly.length;i++){
    const A=poly[i-1], B=poly[i], span=B.t-A.t, steps=Math.max(1,Math.round(span/dt));
    const rate=span>0?(A.d-B.d)/span:0; if(rate>peakRate) peakRate=rate;
    for(let s=1;s<=steps;s++){
      const dd=A.d+(B.d-A.d)*(s/steps), pi=inspN2(dd);
      for(let c=0;c<NC;c++){ const k=1-Math.pow(2,-(span/steps)/HALF[c]); t[c]+=(pi-t[c])*k; }
      const overM=(ceilingFsw(t) - dd*M_TO_FSW)/M_TO_FSW;   // metres above the ceiling
      if(overM>maxOverM) maxOverM=overM;
      if(overM>0) minutesOver += span/steps;
    }
  }
  let st=0; for(let c=0;c<NC;c++){ const r=t[c]/mSurface(c); if(r>st) st=r; }
  return {maxOverM, minutesOver, finalLoad:st, peakRate};
}
/* The square dive the 3-scalar model implicitly assumes: descend, sit at depth
   for `bottom`, ascend linearly over the diver's ACTUAL ascent time. */
function squareFromScalars(sc){
  const dm=sc.maxDepthM, d0=Math.max(dm/18,0.3);
  return [{t:0,d:0},{t:d0,d:dm},{t:d0+sc.bottom,d:dm},{t:d0+sc.bottom+sc.ascent,d:0}];
}
function auditProfile(poly){
  const sc=diveScalars(poly);
  if(!sc) return null;
  const real=walkAudit(poly);
  const square=walkAudit(squareFromScalars(sc));
  const inDistribution = Math.abs(real.maxOverM - square.maxOverM) < 0.15
                      && Math.abs(real.finalLoad - square.finalLoad) < 0.03;
  /* Violation is ONE physical predicate: were you ever more than CEIL_TOL_M
     above your ceiling on the real trajectory. A dive that surfaces bent was
     necessarily over its ceiling near the surface, so this catches surface-bent
     dives too -- without the false alarm that `finalLoad >= 1.0` would raise on
     a correctly-staged deco dive, which surfaces AT the M-value limit (~1.02x)
     by design. The reported sawtooth stays below CEIL_TOL_M (0.5 m over) but is
     caught the other way: its shape does not survive the 3-scalar reduction, so
     it is out of distribution and its rank is withheld regardless. */
  const violated = real.maxOverM > CEIL_TOL_M;
  return {
    maxOverM:real.maxOverM, minutesOverCeiling:real.minutesOver,
    finalLoad:real.finalLoad, peakAscentRate:real.peakRate,
    overCeiling:violated, violated, inDistribution,
    trustRank: inDistribution && !violated
  };
}

function predict(poly){
  const sc=diveScalars(poly);
  if(!sc) return null;
  const P=loadToBottom(sc.depthFsw, sc.bottom);
  const req=requiredAscentMin(P, sc.depthFsw);
  const scored={depthFsw:sc.depthFsw, bottom:sc.bottom, ascent:req.total};
  const score=realScore(scored);
  const deficit=req.total - sc.ascent;          // minutes of obligation skipped
  const audit=auditProfile(poly);
  return {
    score, pct:percentileOf(score),
    depthFsw:sc.depthFsw, bottom:sc.bottom,
    requiredAscent:req.total, requiredStops:req.stop, actualAscent:sc.ascent,
    deficit,
    // physical + epistemic verdict from the continuous audit
    maxOverM:audit.maxOverM, minutesOverCeiling:audit.minutesOverCeiling,
    finalLoad:audit.finalLoad, overCeiling:audit.overCeiling,
    surfacedBent:audit.surfacedBent, violated:audit.violated,
    inDistribution:audit.inDistribution, trustRank:audit.trustRank,
    multilevel: sc.multilevel,
    drivers: realDrivers(scored),
    cohortRate: cohortDecileRate(percentileOf(score))
  };
}
function percentileOf(score){
  if(score<=RM_Q[0]) return 0;
  if(score>=RM_Q[RM_Q.length-1]) return 1;
  for(let i=1;i<RM_Q.length;i++){
    if(score<=RM_Q[i]){
      const lo=RM_Q[i-1], hi=RM_Q[i], f=hi>lo?(score-lo)/(hi-lo):0;
      return ((i-1)+f)/(RM_Q.length-1);
    }
  }
  return 1;
}
/* Which of the three actually moved this dive's score, in standardised units. */
function realDrivers(sc){
  const x=[sc.depthFsw, sc.bottom, sc.ascent];
  const names=['max depth','bottom time','ascent time'];
  return names.map((n,i)=>({
    name:n,
    z: RM.coef[i]*((x[i]-RM.mean[i])/RM.scale[i]),
    confounded: i===2
  })).sort((a,b)=>Math.abs(b.z)-Math.abs(a.z));
}
function cohortDecileRate(pct){
  return RM.decile[Math.max(0,Math.min(9,Math.floor(pct*10)))];
}

/* One verdict from the profile audit, read by every surface. Physical danger
   first (over the ceiling), then the epistemic one (the model can't see this
   dive shape). Either withholds the rank -- a reassuring number the user acts
   on is the failure mode, so both suppress it, with an honest reason. */
function voidVerdict(r){
  if(!r) return {voided:false, band:'', reason:''};
  if(r.violated){
    const mins = r.minutesOverCeiling>=0.05 ? ' for '+r.minutesOverCeiling.toFixed(1)+' min' : '';
    return {voided:true, band:'⚠ OVER YOUR CEILING · MODEL VOID',
            reason:'you were '+r.maxOverM.toFixed(1)+' m above your ceiling'+mins};
  }
  if(!r.inDistribution){
    return {voided:true, band:'⚠ MODEL CAN’T SEE THIS DIVE',
            reason:'this profile does not reduce to the three numbers the model reads, so its rank is meaningless'};
  }
  return {voided:false, band:'', reason:''};
}

function simulatePolyline(poly){
  let t=HALF.map(()=>inspN2(0)); const dt=0.02;
  for(let i=1;i<poly.length;i++){
    const a=poly[i-1], b=poly[i], span=b.t-a.t, steps=Math.max(1,Math.round(span/dt));
    for(let s=1;s<=steps;s++){ const dd=a.d+(b.d-a.d)*(s/steps), pi=inspN2(dd);
      for(let c=0;c<NC;c++){ const k=1-Math.pow(2,-(span/steps)/HALF[c]); t[c]+=(pi-t[c])*k; } }
  }
  let st=0,li=0; for(let c=0;c<NC;c++){ const r=t[c]/mSurface(c); if(r>st){st=r;li=c;} }
  return {st,li,tissue:t};
}

