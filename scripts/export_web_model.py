"""Export the real, data-fitted model for the DecoStress web app.

What ships to the browser is ONLY what survived the benchmark:

  * the real Bühlmann ZHL-16C table (16 compartments, a/b coefficients) --
    for the tissue-loading visualisation, which is genuine physics;
  * a logistic on the three raw dive scalars (depth, bottom time, ascent
    time) fitted to real NMRC 99-02 outcomes -- the ONLY thing in this
    project that carries real signal, and it is weak (grouped-CV AUC ~0.64).

What does NOT ship, and why:

  * Any probability. AUC is a ranking. The ~16% DCS rate in these data comes
    from Navy trials *designed to provoke DCS*; a probability derived from it
    is meaningless for a real diver. The web app emits a PERCENTILE RANK
    within this cohort, never a P(DCS).
  * Any physiological term (PFO, hydration, sleep, fitness, age). The real
    data has no such columns -- there is nothing to fit them to. They were
    only ever "validated" against synthetic labels the author invented.
  * The bubble model, and the Bühlmann risk_index/deficit features. All
    scored NOT SUPPORTED against real outcomes (see RESULTS.md).

The honest out-of-sample skill is the grouped-CV AUC, not the fit on all
data. Both are exported; the app must display the former.

Usage:
    python scripts/export_web_model.py [--out web_model.json]
"""
from __future__ import annotations

import argparse
import json
import subprocess

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold
from sklearn.preprocessing import StandardScaler

from benchmark.buhlmann import zhl16c_table
from benchmark.evaluate import C_GRID, baseline_auc, _fit_score
from scripts.run_benchmark import REAL_CSV, load_dives

FEATURES = ("depth_fsw", "bottom_time_min", "ascent_time_min")


def _git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], text=True).strip()
    except Exception:
        return "unknown"


def pick_C(X, y, groups, seed: int = 0, n_inner: int = 3) -> float:
    """Choose C by grouped CV -- the same way the benchmark's inner loop does."""
    gi = np.array([{g: i for i, g in enumerate(np.unique(groups))}[g] for g in groups])
    best_C, best = C_GRID[0], -np.inf
    for C in C_GRID:
        scores = [
            _fit_score(C, X[tr], y[tr], X[te], y[te])
            for tr, te in GroupKFold(n_inner).split(X, y, gi)
            if len(np.unique(y[te])) >= 2
        ]
        if scores and np.mean(scores) > best:
            best, best_C = float(np.mean(scores)), C
    return best_C


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="web_model.json")
    ap.add_argument("--marginal", default="exclude",
                    choices=("exclude", "positive", "negative"))
    args = ap.parse_args()

    dives, y, groups, report = load_dives(None, args.marginal)
    X = np.array([[d.depth_fsw, d.bottom_time_min, d.ascent_time_min]
                  for d in dives], float)

    # Honest out-of-sample skill: nested grouped CV. This is the number the app
    # must show. Anything fitted-on-all-data would flatter the model.
    auc_folds = baseline_auc(X, y, groups, n_rep=5, seed=0)
    auc_mean, auc_sd = float(auc_folds.mean()), float(auc_folds.std())

    # The deployable model: fit on everything, C chosen by grouped CV.
    C = pick_C(X, y, groups)
    scaler = StandardScaler().fit(X)
    clf = LogisticRegression(C=C, max_iter=5000).fit(scaler.transform(X), y)

    # Score every real dive so the browser can place a new dive as a PERCENTILE
    # within this cohort. A percentile is a ranking -- which is all an AUC of
    # 0.64 licenses us to claim.
    scores = clf.decision_function(scaler.transform(X))
    order = np.argsort(scores)
    ref = np.quantile(scores, np.linspace(0.0, 1.0, 101))  # 101 breakpoints

    # Observed DCS rate by score decile, IN THIS COHORT ONLY. Reported so the
    # app can show what the ranking is actually worth, and how flat it is.
    deciles = np.quantile(scores, np.linspace(0, 1, 11))
    dec_rate = []
    for i in range(10):
        lo, hi = deciles[i], deciles[i + 1]
        m = (scores >= lo) & (scores <= hi if i == 9 else scores < hi)
        dec_rate.append(float(y[m].mean()) if m.sum() else None)

    out = {
        "_comment": "GENERATED by scripts/export_web_model.py. Do not hand-edit.",
        "provenance": {
            "git": _git_sha(),
            "csv": REAL_CSV,
            "marginal": args.marginal,
            "n_dives": int(len(dives)),
            "n_dcs": int(y.sum()),
            "dcs_rate": float(y.mean()),
            "n_total_before_bounce_filter": report.n_total,
            "n_dropped": report.n_dropped,
            "dropped_dcs_rate": report.dropped_dcs_rate,
            "kept_dcs_rate": report.kept_dcs_rate,
        },
        "skill": {
            "auc_grouped_cv": auc_mean,
            "auc_sd": auc_sd,
            "note": ("Honest out-of-sample estimate, nested grouped CV by dive "
                     "trial. This is a RANKING skill. 0.5 is a coin flip; a "
                     "useful clinical test is 0.85+."),
        },
        "model": {
            "kind": "logistic_on_raw_scalars",
            "features": list(FEATURES),
            "C": float(C),
            "scaler_mean": scaler.mean_.tolist(),
            "scaler_scale": scaler.scale_.tolist(),
            "coef": clf.coef_[0].tolist(),
            "intercept": float(clf.intercept_[0]),
            "emits": "percentile_rank_within_cohort",
            "never_emits": "probability_of_dcs",
        },
        "cohort_score_quantiles": ref.tolist(),
        "cohort_decile_dcs_rate": dec_rate,
        "zhl16c": {
            "note": ("Real Bühlmann ZHL-16C. half_time_min, a, b per "
                     "compartment. Used for the tissue visualisation only -- "
                     "it scored NOT SUPPORTED as a DCS predictor."),
            "half_time_min": zhl16c_table()[:, 0].tolist(),
            "a": zhl16c_table()[:, 1].tolist(),
            "b": zhl16c_table()[:, 2].tolist(),
        },
    }

    with open(args.out, "w") as f:
        json.dump(out, f, indent=2)

    print(f"wrote {args.out}")
    print(f"  n={len(dives)} dives, {int(y.sum())} DCS ({y.mean():.1%})")
    print(f"  grouped-CV AUC = {auc_mean:.4f} ± {auc_sd:.4f}   <- the honest number")
    print(f"  C = {C}")
    print(f"  coef (standardised) = {dict(zip(FEATURES, np.round(clf.coef_[0], 4)))}")
    print(f"  intercept = {clf.intercept_[0]:.4f}")
    print(f"  decile DCS rate = {[round(r, 3) if r is not None else None for r in dec_rate]}")


if __name__ == "__main__":
    main()
